#!/usr/bin/env node
/**
 * build-static-icons.mjs — status glyphs as standalone single-colour SVG files, for surfaces that
 * cannot run <aha-icon>: report images rendered to PNG (matplotlib, Pillow, cairosvg, a headless
 * screenshot), email and exports.
 *
 *   lib/static-icons/<ink>/<size>/<name>.svg     ink: ink (#1A1A1A) | white (#FFFFFF) · size: 12 | 16 | 24 | 32
 *   lib/static-icons/manifest.json              names, roles, sizes, inks and paths
 *
 * Each file is generated from icons/registry.json under the registry's own name, with the colour
 * baked in (no currentColor, which a PNG renderer cannot resolve) and the stroke drawn at the same
 * pixel width <aha-icon> uses at that size. Never edit the output by hand: change the registry or
 * STATIC_GLYPHS and re-run.
 *
 *   node build-static-icons.mjs           write the files
 *   node build-static-icons.mjs --check   exit 1 when lib/static-icons is out of date
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LINE, strokeWidthFor } from './lib/icons.js';

const root = dirname(fileURLToPath(import.meta.url));
const OUT = join(root, 'lib', 'static-icons');
const registry = JSON.parse(readFileSync(join(root, 'icons', 'registry.json'), 'utf8')).icons;
const colours = JSON.parse(readFileSync(join(root, 'tokens.canonical.json'), 'utf8')).color;

const STATIC_GLYPHS = [
  { name: 'system-arrow-up', role: 'rise: a figure went up (black, beside the number)' },
  { name: 'system-arrow-down', role: 'fall: a figure went down (white, on the black pill)' },
  { name: 'system-minus', role: 'no change against the previous period' },
  { name: 'system-trend-up', role: 'an upward trend over several periods' },
  { name: 'system-trend-down', role: 'a downward trend over several periods' },
  { name: 'system-warning-circle', role: 'warning: a figure needs attention, or data is incomplete' },
  { name: 'system-hourglass-high', role: 'pending: data still loading or waiting on a source' },
  { name: 'system-circle-dashed', role: 'not started' },
  { name: 'system-circle-half-dashed', role: 'in progress' },
  { name: 'system-check-circle', role: 'completed or done' },
];
const STATIC_INKS = { ink: colours.textDefault, white: colours.textInverse };
const STATIC_SIZES = Object.keys(LINE).map(Number);

function svgFor(name, ink, size) {
  const glyph = registry[name];
  const stroke = strokeWidthFor(size, glyph.viewBox);
  const body = glyph.body
    .replace(/currentColor/g, ink)
    .replace(/stroke-width="[^"]*"/g, `stroke-width="${stroke}"`);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="${glyph.viewBox}" fill="none">${body}</svg>\n`;
}

function expectedFiles() {
  const files = new Map();
  const manifest = {
    $about: 'Generated by build-static-icons.mjs from icons/registry.json; do not edit by hand. Single-colour status glyphs for report images, email and exports, under the registry names.',
    path: 'lib/static-icons/<ink>/<size>/<name>.svg',
    inks: STATIC_INKS,
    sizes: STATIC_SIZES,
    glyphs: STATIC_GLYPHS.map(({ name, role }) => ({ name, role })),
  };
  for (const { name } of STATIC_GLYPHS) {
    if (!registry[name]) throw new Error(`build-static-icons: "${name}" is not in icons/registry.json`);
    for (const [inkName, ink] of Object.entries(STATIC_INKS)) {
      for (const size of STATIC_SIZES) files.set(join(OUT, inkName, String(size), `${name}.svg`), svgFor(name, ink, size));
    }
  }
  files.set(join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
  return files;
}

function filesOnDisk(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory).flatMap((entry) => {
    const path = join(directory, entry);
    return statSync(path).isDirectory() ? filesOnDisk(path) : [path];
  });
}

const expected = expectedFiles();
if (process.argv.includes('--check')) {
  const stale = [...expected].filter(([path, content]) => !existsSync(path) || readFileSync(path, 'utf8') !== content).map(([path]) => path);
  const extra = filesOnDisk(OUT).filter((path) => !expected.has(path));
  if (stale.length || extra.length) {
    for (const path of [...stale, ...extra]) console.error(`  ✗ ${relative(root, path)}`);
    console.error('lib/static-icons is out of date: run node build-static-icons.mjs');
    process.exit(1);
  }
  console.log(`  ✓ lib/static-icons up to date (${expected.size - 1} glyph files)`);
} else {
  for (const [path, content] of expected) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  console.log(`  ✓ lib/static-icons — ${STATIC_GLYPHS.length} glyphs × ${Object.keys(STATIC_INKS).length} inks × ${STATIC_SIZES.length} sizes`);
}
